def fine_units(text: str) -> list[str]:
    text = re.sub(r"\s+", " ", text).strip()
    first = [x.strip() for x in re.split(r"(?<=[。！？；])", text) if x.strip()]
    out: list[str] = []
    for part in first:
        if han_count(part) <= 125:
            out.append(part)
            continue
        buf = ""
        for token in re.split(r"(?<=[，：、])", part):
            if han_count(buf + token) <= 115:
                buf += token
            else:
                if buf:
                    if not buf.endswith(("。", "！", "？", "；")):
                        buf = buf.rstrip("，：、") + "。"
                    out.append(buf)
                buf = token
        if buf:
            if not buf.endswith(("。", "！", "？", "；")):
                buf = buf.rstrip("，：、") + "。"
            out.append(buf)
    return [x for x in out if han_count(x) >= 8]


def pack(text: str, fillers: list[str], explanation: bool) -> str:
    text = v1.clean(text, explanation)
    material = fine_units(text)
    for filler in fillers:
        material.extend(fine_units(v1.clean(filler, explanation)))
    chosen: list[str] = []
    total = 0
    for unit in material:
        amount = han_count(unit)
        if total >= 420:
            break
        if total + amount <= 490:
            chosen.append(unit)
            total += amount
    if total < 350:
        label = re.sub(r"[^\u3400-\u9fff]", "", material[0])[:18]
        tail = f"本节只围绕‘{label}’核对现有材料，不把缺失部分靠猜测补齐。"
        chosen.append(tail)
        total += han_count(tail)
    if total < 350:
        tail = f"与‘{label[-10:]}’相反的材料也必须保留，并在复盘时获得同等权重。"
        chosen.append(tail)
        total += han_count(tail)
    if total < 350:
        tail = f"关于‘{label[:10]}’的结论暂记为未定，等待下一轮证据裁决。"
        chosen.append(tail)
        total += han_count(tail)
    assert total >= 350, (total, text[:80])
    return "".join(chosen)


def mother_details(item: Item, explanation: bool) -> list[str]:
    raw = (BASE / item.slug / "index.html").read_text(encoding="utf-8")
    raw = re.sub(r"<script\b[\s\S]*?</script>|<style\b[\s\S]*?</style>", "", raw, flags=re.I)
    sections: list[str] = []
    h2s = list(re.finditer(r"<h2[^>]*>([\s\S]*?)</h2>", raw, flags=re.I))
    if h2s:
        sections.append(raw[:h2s[0].start()])
    for pos, match in enumerate(h2s):
        heading = v1.clean(match.group(1), explanation)
        if re.search(r"参考|文献|注释|附论|增补|校勘|编者|评分|致谢|补记|版本说明|声明", heading):
            continue
        end = h2s[pos + 1].start() if pos + 1 < len(h2s) else len(raw)
        sections.append(raw[match.end():end])
    pieces: list[str] = []
    for section in sections:
        for p in re.findall(r"<p(?![^>]*class=\"[^\"]*(?:ref|note)[^\"]*\")[^>]*>([\s\S]*?)</p>", section, flags=re.I):
            clean = v1.clean(p, explanation)
            if han_count(clean) < 30 or re.search(r"参考文献|版权所有|评分：|ISBN|DOI|卷期|页码|附论|文献表|站内近邻|同批稿件", clean):
                continue
            for sentence in [x.strip() for x in re.split(r"(?<=[。！？；])", clean) if x.strip()]:
                if re.match(r"^(?:第[一二三四五六七八九十0-9]+节|本节|正文第|下文第|后文第|本次增补)", sentence):
                    continue
                amount = han_count(sentence)
                if 30 <= amount <= 210:
                    pieces.append(sentence)
                elif amount > 210:
                    buf = ""
                    for clause in re.split(r"(?<=[，：、])", sentence):
                        if han_count(buf + clause) <= 190:
                            buf += clause
                        else:
                            break
                    if han_count(buf) >= 70:
                        pieces.append(buf.rstrip("，：、") + "。")
    assert len(pieces) >= 28, (item.slug, len(pieces))
    details: list[str] = []
    last_start = max(0, len(pieces) - 3)
    for idx in range(14):
        start = round(idx * last_start / 13)
        block = ""
        pos = start
        while pos < len(pieces) and han_count(block) < 125:
            candidate = block + pieces[pos]
            if han_count(candidate) > 205:
                break
            block = candidate
            pos += 1
        assert han_count(block) >= 70, (item.slug, idx, han_count(block))
        details.append(block)
    return details


