def audit(built: dict[tuple[str, str], list[dict[str, str]]], first_slugs: set[str]) -> None:
    report = {"student": "张琼", "date": "2026-08-13", "batch": 2, "pairs": 20, "non_overlap_with_batch_1": True, "pages": []}
    second_slugs = {item.slug for item in ITEMS}
    assert not (first_slugs & second_slugs)
    for item in ITEMS:
        for kind in ("explain", "practice"):
            sections = built[(item.slug, kind)]
            counts = [han_count(section["text"]) for section in sections]
            route = "interpretation" if kind == "explain" else "practice"
            source = (BASE / item.slug / route / "source.txt").read_text(encoding="utf-8")
            assert len(sections) == 14 and len(re.findall(r"^== ", source, flags=re.M)) == 14
            assert sum(counts) >= 4800 and all(350 <= n <= 500 for n in counts)
            assert source.startswith("TITLE: ") and "\nSUB: " in source and "\nABS: " in source
            headings = re.findall(r"^==\s+(.+)$", source, flags=re.M)
            assert not any(re.match(r"^[一二三四五六七八九十百]+[、.．]|^\d+[、.．]", h) for h in headings)
            body = "\n".join(section["text"] for section in sections)
            sentence_keys: set[str] = set()
            duplicate_sentences = 0
            for sentence in re.split(r"(?<=[。！？；])", body):
                key = re.sub(r"[\s，。！？；：、‘’“”（）《》〈〉—…·,.!?;:'\"()\[\]-]", "", sentence)
                if han_count(sentence) < 18:
                    continue
                if key in sentence_keys:
                    duplicate_sentences += 1
                sentence_keys.add(key)
            assert duplicate_sentences == 0, (item.slug, kind, duplicate_sentences)
            if kind == "explain":
                assert all(word not in source for word in v1.FORBIDDEN)
                for fixed in ("回到这个日常场景", "把类比再推一步", "它不能被这样误用"):
                    assert fixed in headings
            else:
                for fixed in ("先定位：问题究竟卡在哪一环", "读数、采集办法与代价", "什么时候应该停，什么时候说明理论可能不对"):
                    assert fixed in headings
            report["pages"].append({"slug": item.slug, "kind": kind, "han": sum(counts), "sections": 14, "min_section_han": min(counts), "max_section_han": max(counts), "duplicate_sentences": 0})
    (BASE / "companion-audit-v2.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    manifest_path = BASE / "companion-manifest.json"
    current_manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    first_batch = [row for row in current_manifest["items"] if row.get("batch", 1) == 1][:20]
    assert len(first_batch) == 20
    first_slugs = {row["slug"] for row in first_batch}
    built: dict[tuple[str, str], list[dict[str, str]]] = {}
    for item in ITEMS:
        assert item.slug not in first_slugs
        for kind, route in (("explain", "interpretation"), ("practice", "practice")):
            sections = make_sections(item, kind)
            source = v1.source_text(item, kind, sections)
            if kind == "explain":
                for forbidden, replacement in v1.FORBIDDEN.items():
                    source = source.replace(forbidden, replacement)
            out_dir = BASE / item.slug / route
            out_dir.mkdir(parents=True, exist_ok=True)
            (out_dir / "source.txt").write_text(source, encoding="utf-8")
            page = v1.render(item, kind, sections, source)
            if kind == "explain":
                for forbidden, replacement in v1.FORBIDDEN.items():
                    page = page.replace(forbidden, replacement)
            (out_dir / "index.html").write_text(page, encoding="utf-8")
            built[(item.slug, kind)] = sections
        update_mother(item)
        v1.redirect(BASE / item.slug / "explain.html", f"/students/zhang-qiong/{item.slug}/interpretation/")
        v1.redirect(BASE / item.slug / "practice.html", f"/students/zhang-qiong/{item.slug}/practice/")
    update_manifest(first_batch)
    update_works(first_batch)
    audit(built, first_slugs)
    pages = json.loads((BASE / "companion-audit-v2.json").read_text(encoding="utf-8"))["pages"]
    print(f"built second batch: {len(ITEMS)} pairs / {len(pages)} pages; Han range {min(p['han'] for p in pages)}-{max(p['han'] for p in pages)}")


if __name__ == "__main__":
    main()
