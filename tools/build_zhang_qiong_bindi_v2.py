def make_sections(item: Item, kind: str) -> list[dict[str, str]]:
    explanation = kind == "explain"
    details = mother_details(item, explanation)
    headings = EXPLAIN_HEADINGS[:] if explanation else PRACTICE_HEADINGS[:]
    if explanation:
        headings[10] = f"它和{item.neighbour}相邻，但不是一回事"
    sections: list[dict[str, str]] = []
    for idx in range(14):
        candidate = explain_candidate(item, idx, details[idx]) if explanation else practice_candidate(item, idx, details[idx])
        fillers = ([EXPLAIN_FILLERS[idx], section_extension(item, kind, idx)]
                   if explanation else
                   [PRACTICE_FILLERS[idx], section_extension(item, kind, idx)])
        text = pack(candidate, fillers, explanation)
        sections.append({"heading": headings[idx], "text": text})
    return sections


