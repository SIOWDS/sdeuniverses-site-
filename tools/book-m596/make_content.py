def info(n):
    md = (CH / ('ch%02d.md' % n)).read_text(encoding='utf-8')
    title = re.match(r'^## 第 \d+ 章　(.*)$', md.splitlines()[0])[1].strip()
    secs = [re.sub(r'^◆\s*第.节\s*', '', s).strip() for s in re.findall(r'^### (.*)$', md, re.M)]
    paras = [p.strip() for p in md.split('\n\n') if p.strip() and not p.startswith('#')]
    last = paras[-1] if paras else ''
    last = re.sub(r'[\*　]', '', last)
    m = re.match(r'^(.{60,170}?[。！？])', last)
    return title, secs, (m[1] if m else last[:160])


