def conv(n, t, chapter=True):
    L = t.strip().split('\n'); title = L[0].lstrip('# ').strip(); res = []
    if chapter: res.append('## ' + title)
    led = False
    for l in L[1:]:
        s = l.strip()
        if not s: continue
        if s.startswith('◆'):
            res.append('### ' + s); led = False; continue
        m = re.match(r'^\*\*带走的话\*\*[：:]\s*(.*)$', s)
        if m: res.append('【带走的话】' + m.group(1)); continue
        if re.match(r'^两行小账[：:]?$', s): led = True; continue
        if led and s.startswith('- '):
            res.append('【小账】' + s[2:]); continue
        led = False
        res.append(s)
    return res
