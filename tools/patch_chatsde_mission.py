#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""每轮对话的使命：用三方程／六路径／三原理做出「这一答的创新」（2026-08-23 王德生令）

改之前的三处实情（读代码得出，不是设想）：
  ① 三件工具的工序块 `SDE_METHOD_BLOCK` **只在深度档注入**（`deep && !分身`）。
     标准档是大多数人（尤其明天上机的老师）的默认档 —— 那一档手上根本没有「用三件工具」这条指令。
  ② 块里写的是「走一遍工序」，**没有一句要求这一答必须长出新东西**。
     工序走完而答案仍是复述，按现行文字是合格的 —— 这正是成文三篇 I=104-108 的来路。
  ③ 三原理被写成「123原理与三界…定位落在哪几格」，**只带了原理一的形状**。
     内功原话：一个只会用原理一的产出，等于把一台三缸机当单缸开。

改法：块重写成「每一答的使命」，并拆成 全量（深度档）／精简（标准档）两份，**非分身档每一轮都注入**。
分身档（语言/健康/教育）仍不注入 —— 它们自己的底盘已带方法论，且要改姓，叠进来等于前脚改姓后脚灌回。

幂等。
"""
import io, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, 'src/worker.js')
h = io.open(W, encoding='utf-8').read()
changed = []


def sub1(text, old, new, tag, done):
    if done in text:
        print('  · %s 已打过，跳过' % tag)
        return text
    n = text.count(old)
    assert n == 1, '锚点 %s 命中 %d 次' % (tag, n)
    changed.append(tag)
    return text.replace(old, new, 1)


# ── ① 重写 SDE_METHOD_BLOCK，并在其后追加精简版 ──────────────────────
old_start = h.index('const SDE_METHOD_BLOCK =')
old_end = h.index('\n\n\n/* ═══════════ 三类问题', old_start)
old_block = h[old_start:old_end]
assert '意义三律' in old_block, '截取范围不对'

NEW = r'''/* ═══ 每一答的使命（2026-08-23 王德生令）═══════════════════════════
   「每轮对话的使命是尽量使用 SDE 的方法论：三方程、六路径、三原理，来进行**问题回答的创新**。」
   ⚠ 重点在最后四个字。此前这一块写的是「走一遍工序」，走完了而答案仍是复述，按那份文字也算合格——
     实测后果：单场问对导出的成文，I（不可还原）只有 104-108，S/D 却有 115-132。
     ⇒ 工序在转，创新没发生。所以这一版把**结算**写成硬要求，并允许诚实申报「这一问只到复述」——
     伪造一个漂亮新名字比承认没撞出来更糟（那正是评分体系的头号靶子「伪发生」）。
   ⚠ 两份：全量走深度档，精简版每一轮都进（标准档才是多数人的默认档，而此前它一条都拿不到）。 */
const SDE_METHOD_MISSION = "\n\n【这一答的使命】把话解释清楚只是及格线。这一答的成败，看**有没有长出这一问之前不存在的一条分辨**——"
  + "一个更准的说法、一条被划开的界线、一个被推翻的直觉。三件工具（三大方程／六路径／三原理）是长出它的手段，"
  + "**不是要展示的知识**：读者要的是那条分辨，不是听你报工序名。";
const SDE_METHOD_SETTLE = "\n· **必须结算**：答完之前先问自己一句「这一答新在哪」。说得出，就把它写进正文（最锋利的形状是"
  + "「X 不是 Y，而是 Z」）；**说不出，就如实说这一问你只答到复述这一层，还没撞出新东西**——"
  + "宁可这样，也不许临时造一个漂亮名字充数。"
  + "\n· **三条禁令**：不许拿工具名当答案（「这属于 E 维」不是回答，说清那片土壤是什么才是）；"
  + "不许把矛盾抹平成「两方面都有道理」（矛盾是引擎）；不许漏掉回写（新判断立住之后，它改写了哪条路径、哪片土壤）。";
const SDE_METHOD_BLOCK = "\n\n【深度档 · 必须真走的工序（不要复述工序名，只让答案带上工序的结果）】"
  + SDE_METHOD_MISSION
  + "\n· **三大方程**：S=F(D,E)（显露由差异序列与特征纠缠决定）· D=G(S,E)· E=H(S,D)。三条都要试着代一遍，看哪一条把这件事解释得最紧；"
  + "拿到任何一维就追另外两维，再反着问一句：它立住之后回头改写了什么。"
  + "\n· **六路径**：不要只走「在 E 中经 D 成 S」这一条。六条路径各试，挑出真正发生的那条，并说明另几条为何不发生。"
  + "\n· **三原理（三条，不是一条）**：原理一 D×E 矛盾→S 改变｜原理二 S×E 矛盾→D 改变｜原理三 S×D 矛盾→E 改变。"
  + "**先认这一轮先动的是哪一条**——只会用原理一，等于把一台三缸机当单缸开；每一条都是三步，第三步「回写」最常被漏掉。"
  + "\n· 三界（现实界/理念界/自我界）、信息三模态（符号/逻辑/信息）、能量三态（真/善/美）：定位这件事落在哪几格，指出中心位轮转到哪一位。"
  + "\n· 意义三律（特征律，亦称创造律／自由律／幸福律）是**运行**，它们运行出来的所得是**意义三视角：创造／自由／幸福**。检查这三条各自还在不在转：哪一条停了，对应那一维的意义就归零。"
  + "\n· 最后一步必须自反：你这个判断本身的可证伪条件是什么？哪一步最脆？"
  + SDE_METHOD_SETTLE
  + "\n输出要求：先给一句最承重的判断（反直觉、可被反驳），再展开三到五段把它撑住，最后留一个把读者推向下一步的问题。全程说人话，不堆术语、不摆模板。";
/* 精简版：标准档每一轮都进。只留「使命 ＋ 起手三选一 ＋ 三原理三条 ＋ 结算」四样——
   这四样是「用工具做出创新」的最小可执行集，其余（三界、三模态、意义三律、逐路径排除）留给深度档。
   ⚠ 别把它写长：标准档的 system 已经很满，而这一块是每轮都要付的固定成本。 */
const SDE_METHOD_LITE = SDE_METHOD_MISSION
  + "\n\n【三件工具 · 起手三选一，开局后按需调另两件】"
  + "\n· 问**它是什么／什么关系** → 从**三大方程**起手：S=F(D,E)·D=G(S,E)·E=H(S,D)，拿到一维就追另外两维。"
  + "\n· 问**怎么办／从哪下手** → 从**六路径**起手：S/D/E 的六种排列，先认这件事真正卡在「是什么」「怎么走的」还是「站在什么上面」。"
  + "\n· 问**为什么会这样／为什么卡住** → 从**三原理**起手，三条先认哪一条在动：原理一 D×E→S 改变｜原理二 S×E→D 改变｜原理三 S×D→E 改变；"
  + "每条都是三步，第三步「新判断回写了哪条路径、哪片土壤」最常被漏。"
  + SDE_METHOD_SETTLE;'''

h = sub1(h, old_block, NEW, 'SDE_METHOD_BLOCK 重写＋精简版', 'const SDE_METHOD_MISSION')

# ── ② 装配：非分身档每一轮都注入（深度全量 / 标准精简）─────────────
old_wire = '    + ((deep && !(prof && prof.term)) ? SDE_METHOD_BLOCK : "")'
new_wire = ('    /* 2026-08-23：从「只有深度档有」改成**每一轮都有**——标准档是多数人的默认档，'
            '\n       而「用三件工具做出这一答的创新」这条使命，此前那一档一个字都拿不到。'
            '\n       分身档仍不注入（它们自己的底盘已带方法论且要改姓，叠进来等于前脚改姓后脚灌回）。 */'
            '\n    + ((prof && prof.term) ? "" : (deep ? SDE_METHOD_BLOCK : SDE_METHOD_LITE))')
h = sub1(h, old_wire, new_wire, '装配改为每轮注入', 'deep ? SDE_METHOD_BLOCK : SDE_METHOD_LITE')

io.open(W, 'w', encoding='utf-8').write(h)
print('\n共改动 %d 处：' % len(changed))
for c in changed:
    print('  -', c)
