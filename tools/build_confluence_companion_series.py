def main() -> None:
    for no, t in enumerate(THEORIES, 1):
        t["no"] = no
        for mode, builder in (("explained", build_plain), ("applied", build_applied)):
            out = builder(t)
            count = visible_count(out)
            # Chinese Han count excludes punctuation, Latin field names and digits. 4.3k Han
            # corresponds to roughly five thousand visible Chinese article characters.
            if count < 4300:
                raise RuntimeError(f"{t['slug']}/{mode} only {count} Chinese chars")
            dest = CF / t["slug"] / mode / "index.html"
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(out, encoding="utf-8")
            print(f"built {dest.relative_to(ROOT)}: {count} Chinese chars")
        inject_mother(t)
    dest = CF / "companion-series" / "index.html"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(catalog(), encoding="utf-8")
    wire_indexes()
    print("wired catalog, mother pages, confluence index and homepage")


if __name__ == "__main__":
    main()
