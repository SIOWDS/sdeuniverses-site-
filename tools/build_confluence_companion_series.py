def esc(s: object) -> str:
    return html.escape(str(s), quote=True)


def P(s: str) -> str:
    return f"<p>{s}</p>"


def H2(i: int, s: str) -> str:
    return f'<h2 id="s{i}">{esc(s)}</h2>'


def visible_count(text: str) -> int:
    plain = re.sub(r"<script\b.*?</script>|<style\b.*?</style>", "", text, flags=re.S | re.I)
    plain = re.sub(r"<[^>]+>", "", plain)
    return len(re.findall(r"[\u3400-\u9fff]", html.unescape(plain)))


