def main():
    rows = []
    for f in sorted(SRC.glob('[0-3][0-9]_*.md')):
        t = f.read_text()
        title = t.splitlines()[0].lstrip('# ').strip()
        i = t.find('> **小账**')
        if i < 0:
            continue
        items = []
        for ln in t[i:].splitlines()[1:]:
            if not ln.startswith('>'):
                if ln.strip():
                    break
                continue
            s = ln[1:].strip()
            if '待核' in s or '待以原始出处' in s or '尚待' in s:
                items.append(s)
        if items:
            rows.append((title, items))
    out = APPX1 + APPX2_HEAD
    for title, items in rows:
        out += '**%s**\n\n' % title
        for s in items:
            out += '- %s\n' % s
        out += '\n'
    out += APPX2_TAIL
    (ROOT / 'back_src.md').write_text(out)
    print('chapters with pending items:', len(rows), 'items:', sum(len(x) for _, x in rows))


if __name__ == '__main__':
    main()
