def main():
    kps, tasks = [], []
    for f in sys.argv[1:]:
        d = json.loads(Path(f).read_text(encoding='utf-8'))
        kps += d['keypoints']; tasks += d['tasks']
    order = lambda k: 0 if k['ch'].startswith('导论') else (99 if k['ch'].startswith('结语') else int(k['ch'].split('章')[0].replace('第', '').strip()))
    kps.sort(key=order)
    tasks.sort(key=lambda t: t['lesson'])
    assert [t['lesson'] for t in tasks] == list(range(1, 30)), [t['lesson'] for t in tasks]
    assert len(kps) == 31, len(kps)
    C['tasks'] = tasks; C['keypoints'] = kps
    (HERE / 'content.json').write_text(json.dumps(C, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print('content.json ok', len(tasks), len(kps))

if __name__ == '__main__':
    main()
