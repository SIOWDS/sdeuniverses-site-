/* 只测一件事：**上一轮结尾留下的那句追问，有没有落进下一轮的输入框**。

   病史（2026-08-21 用户截图报的）：深度档提示词明写着「最后留一个把前面前提再往深追一层的
   升维追问」（worker.js 两处 ＋「结尾留一个可追问的问题」一处），于是答案末尾自己就留了一句下一问；
   而输入框里填的却是 nextq 按阶梯另拟的一句。屏幕上同时挂着两个不同的「下一问」——
   读者读完最后那句，低头一看输入框里是另一句。两句都对，摆在一起就是错的。

   用户原话：「每次问对的最后一段的『追问的问题』的内容，要自动解析放到第二次问对的『输入框』里面。
   现在的第二次问对的问题和这个『追问』不匹配。要修改。」

   钉三件：解析器认得准（这是全部风险所在）、结尾那句优先落袋、阶梯问法降为备选但不丢。 */
"use strict";
const fs = require("fs");
const H = fs.readFileSync("/home/claude/site/public/search/index.html", "utf8");
const W = fs.readFileSync("/home/claude/site/src/worker.js", "utf8");

let P = 0, F = 0;
const ok = (c, m) => { c ? (P++, console.log("  PASS " + m)) : (F++, console.log("  FAIL " + m)); };

/* 把解析器抠出来真跑——只读源码「看起来对」证明不了正则认不认得出那句话。 */
const iA = H.indexOf("function tailQuestion(txt){");
const iB = H.indexOf("function useLadderQ(){");
const SRC = iA >= 0 && iB > iA ? H.slice(iA, iB) : "";
ok(!!SRC, "抠得出 tailQuestion（锚点变了就先改本脚本）");
const tailQuestion = new Function(SRC + "\nreturn tailQuestion;")();

console.log("— 一、解析器真跑：认得出，才谈得上填得对 —");
/* ① 用户截图里那一句，逐字照抄（含末尾的**半角**问号——真实输出就是半角，
      正则只认全角的话，线上第一例就落空）。 */
const shot = "（心、身、灵）的张力，再给这个张力一个明确的转换渠道——比如把模糊的焦虑写成具体的问题，"
  + "把身体的不适交给运动，把精神的困顿交给冥想或创作。代价是你得暂时待在不适里，而不是立刻找东西把它盖过去。\n\n"
  + "留一个可追问的问题：当两个人在同一件事里一个感到幸福、一个不感到幸福，差异究竟发生在张力的形成，还是张力的释放?";
ok(tailQuestion(shot) === "当两个人在同一件事里一个感到幸福、一个不感到幸福，差异究竟发生在张力的形成，还是张力的释放?",
   "用户截图那一句，逐字解析得出来（含半角问号）");

/* ② 提示词里的另一种措辞：worker.js 写的是「升维追问」，模型多半照着这个词写 */
ok(tailQuestion("……前面正文。\n\n升维追问：如果把「稳定」本身当成变量，这条结论还站得住吗？")
   === "如果把「稳定」本身当成变量，这条结论还站得住吗？", "「升维追问：…」这种措辞也认得出");
ok(tailQuestion("正文。\n进一步追问：这个前提是谁替我们默认下来的？")
   === "这个前提是谁替我们默认下来的？", "「进一步追问：…」认得出");

/* ⚠ 上面三条都能被②那条兜底路径蒙混过关（变异检验抓到的：把①整段删掉，它们照样绿）。
   所以必须有**只有①做得到**的用例：标记词在，但问号后面还跟着一截尾巴——
   ②那条路会因为「问号后还有大段正文」直接判空，只有①取得出来。
   同理再加一条**半角问号 ＋ 有尾巴**：①的正则若只认全角问号，这一条就落空。 */
const TAIL = "以上只是一个方向，本文不再展开其余细节；读者若有兴趣，可自行按同样的方式一路追问下去，"
  + "也可以换一条线索重新起头，这里就不再一一列举了，留待下一轮再谈。";   // >40 字，足以让②那条路判空
ok(tailQuestion("正文正文。\n升维追问：这条前提到底是谁替我们定下来的？" + TAIL)
   === "这条前提到底是谁替我们定下来的？",
   "标记词分支单独扛得住：问号后还跟着一长截尾巴时，只有它取得出来（②那条路会判空）");
ok(tailQuestion("正文正文。\n留一个可追问的问题：那份代价究竟落在谁头上?" + TAIL)
   === "那份代价究竟落在谁头上?",
   "标记词分支认**半角**问号（真实输出就是半角，只认全角的话线上第一例就落空）");

/* ③ 没有标记词，末尾就是一个光秃秃的问句 */
ok(tailQuestion("一、二、三段正文。最后一段结束了。\n\n那么，被留下的那一份代价究竟由谁承担？")
   === "那么，被留下的那一份代价究竟由谁承担？", "没有标记词时，退回「结尾最后一个问句」");

/* ④ 两道防误认的闸——这是解析器最容易出错的地方，宁可不填也不许填错 */
ok(tailQuestion("他真的理解了吗？当然没有。后面还有很长一段正文，讲的是别的事情，"
  + "而且这一段足够长，长到足以说明那个问号只是行文里的一个反问，不是留在结尾的追问。") === "",
   "行文中的反问不算数（问号后面还有大段正文 ⇒ 不填）");
ok(tailQuestion("正文正文正文。") === "", "结尾没有问句 ⇒ 返回空（宁可不填，也不许填错）");
ok(tailQuestion("") === "" && tailQuestion(null) === "", "空输入不炸");
ok(tailQuestion("是吗？") === "", "过短的问句不算（8 字以下多半是语气词，不是可问的下一问）");
/* ⑤ 只切最近的一句，不许把上一整段吞进来 */
const two = "第一句话讲完了。这里还有第二句，它也不短。\n\n那么真正被推迟的是什么？";
ok(tailQuestion(two) === "那么真正被推迟的是什么？", "往回只切到最近的句读／换行，不吞上一段");
/* ⑥ 引导语粘在前面时要剥干净 */
ok(tailQuestion("正文。\n留一个可追问的问题：它凭什么必须由同一个人承担？")
   === "它凭什么必须由同一个人承担？", "引导语与冒号一并剥掉，不许把「留一个可追问的问题：」当成问句的一部分");

console.log("— 二、接线：结尾那句优先落袋，且不许抢用户正在敲的字 —");
const iS = H.indexOf("function suggestNextQ(){");
const BLK = iS >= 0 ? H.slice(iS, H.indexOf("/* ================= 🚀 自动二十轮", iS)) : "";
ok(!!BLK, "抠得出 suggestNextQ");
ok(/var tailQ=tailQuestion\(lastAns\);/.test(BLK), "每轮答完先解析上一轮结尾那句");
ok(BLK.indexOf("if(tailQ && mayFill()){ qa.value=tailQ; nextQReady=tailQ; }") > 0
   && BLK.indexOf("if(tailQ && mayFill())") < BLK.indexOf("return fetch("),
   "**不等 nextq 回来就填**——它已经在屏幕上了，输入框要立刻与它一致，不能先显示另一句再被换掉");
/* 这条纪律比功能本身更要紧：抢走用户正在敲的字，比填错还糟。 */
ok(/var v=qa\.value\.trim\(\);[\s\S]{0,200}return !v \|\| qNorm\(v\)===qNorm\(lastQ\)/.test(BLK),
   "只在输入框为空／仍是上一句／仍是我们上次填的那句时才替换（用户在自己敲字时一个字都不许抢）");
ok(/\(nextQReady && qNorm\(v\)===qNorm\(nextQReady\)\)/.test(BLK),
   "「我们上次填进去的那句」也算可替换（否则第二轮起就再也填不进去了）");

console.log("— 三、阶梯问法降为备选，但一句都不许丢 —");
ok(/ladderQReady=d\.q; ladderMove=d\.move\|\|'';/.test(BLK), "阶梯那一句照旧收下，只是不再直接写进输入框");
ok(/if\(tailQ\)\{[\s\S]{0,700}onclick="useLadderQ\(\)"/.test(BLK),
   "有结尾追问时，阶梯问法只在提示条里给一个一键切换（两句都留着，选择权交给读者）");
ok(/if\(tailQ\)\{[\s\S]{0,800}return;\s*\n/.test(BLK), "走了备选那条路就收手，不再回去动输入框");
ok(BLK.indexOf("nextQReady=d.q;") > BLK.indexOf("if(tailQ){"),
   "结尾没留下追问时（模型没照提示词写）⇒ 照旧退回阶梯那一句，老路径不变");
ok(/function useLadderQ\(\)\{/.test(H) && /qa\.value=ladderQReady/.test(H), "切换函数在位且真的写进输入框");
/* 失败路径：结尾那句是本地解析的，与 nextq 那次调用成败无关 */
ok(/if\(tailQ\) tip\.innerHTML='↓ 已填入上一轮结尾留下的那句追问，可直接问、也可改。/.test(BLK),
   "nextq 调用失败时不许把提示条整条收起来——结尾那句已经填好了，收起来会让读者以为什么都没填");
ok(/turns=\[\]; brief=''; lastAns=''; lastQ=''; nextQReady=''; ladderQReady=''; ladderMove='';/.test(H),
   "清空重来时把两句候选一起清掉（留着上一场的问句会串场）");

console.log("— 四、上游：提示词确实要求了「结尾留一句追问」（解析器的前提）—");
/* 解析器全靠这条提示词兜底。哪天有人把它删了，解析器会静默地一直返回空，
   而页面看起来一切正常——所以这条前提也要钉住。 */
ok(/结尾留一个把前面前提再往深追一层的升维追问/.test(W) || /最后留一个把前面前提再往深追一层的升维追问/.test(W),
   "深度档提示词仍要求「结尾留一个升维追问」（解析器的前提，删了它这功能就静默失效）");

console.log("\n===== " + P + " PASS / " + F + " FAIL =====");
process.exit(F ? 1 : 0);
