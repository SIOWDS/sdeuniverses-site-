def cn_count(t):
    t = re.sub(r'[#>*【】]', '', t)
    return len(re.findall(r'[一-鿿]', t)) + len(re.findall(r'[A-Za-z0-9][A-Za-z0-9.\-]*', t))


def parse(text):
    """正文块：sec/p/dlg/card/sim。"""
    out, lines = [], text.split('\n')[1:]
    i = 0
    while i < len(lines):
        l = lines[i].strip(); i += 1
        if not l:
            continue
        if l.startswith('## '):
            out.append(dict(k='sec', s=l[3:].strip())); continue
        if l.startswith('>'):
            buf = [l]
            while i < len(lines) and lines[i].strip().startswith('>'):
                buf.append(lines[i].strip()); i += 1
            rows = []
            for b in buf:
                b = re.sub(r'^>\s*', '', b)
                if b.replace('*', '') == '答案卡':
                    continue
                m = re.match(r'^([^：]{2,12})：(.*)$', b)
                rows.append([m[1], m[2]] if m else ['', b])
            out.append(dict(k='card', rows=rows)); continue
        m = re.match(r'^(【设想与模拟[^】]*】)\s*(.*)$', l)
        if m:
            out.append(dict(k='sim', s=m[1]))
            if not m[2]:
                continue
            l = m[2]
        if re.match(r'^\*\*[^*]{1,12}：\*\*', l):
            out.append(dict(k='dlg', s=l)); continue
        out.append(dict(k='p', s=l))
    return out


