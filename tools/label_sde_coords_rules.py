def coords_for(text):
    tl = text.lower()
    tags=[]
    for triggers,labels in RULES:
        if any(t.lower() in tl for t in triggers):
            for lb in labels:
                if lb not in tags: tags.append(lb)
    return tags[:20]

man=json.load(open(os.path.join(SD,"manifest.json"),encoding="utf-8"))
doctext={}
for s in man["sections"]:
    for c in json.load(open(os.path.join(SD,"shard-%s.json"%s["key"]),encoding="utf-8"))["chunks"]:
        d=c["d"]
        if len(doctext.get(d,""))<3200: doctext[d]=doctext.get(d,"")+c["t"]+"\n"
coords={}
for d in man["docs"]:
    cs=coords_for(d["t"]+"\n"+doctext.get(d["i"],""))
    if cs: coords[str(d["i"])]=cs
json.dump(coords, open(os.path.join(SD,"sde-coords.json"),"w",encoding="utf-8"), ensure_ascii=False, separators=(",",":"))
from collections import Counter
allt=Counter(); [allt.update(v) for v in coords.values()]
n=len(coords); avg=sum(len(v) for v in coords.values())/max(n,1)
