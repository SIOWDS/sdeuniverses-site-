def norm(lines):
    """章内规范化：小节加 ◆；带走的话统一成引用块。"""
    out, i, n = [], 0, len(lines)
    while i < n:
        ln = lines[i]
        if ln.startswith('### 带走的话'):
            j = i + 1
            while j < n and not lines[j].strip(): j += 1
            t = lines[j].strip(); t = re.sub(r'^\*\*(.*)\*\*$', r'\1', t)
            out += ['> **带走的话**', '> ' + t, '']
            i = j + 1; continue
        m = re.match(r'^\*\*带走的话：(.*)\*\*$', ln)
        if m:
            out += ['> **带走的话**', '> ' + m[1], '']; i += 1; continue
        if ln.startswith('### ') and not ln.startswith('### ◆') and not re.match(r'^### 附录', ln):
            out.append('### ◆ ' + ln[4:]); i += 1; continue
        if ln.strip() == '---':
            i += 1; continue
        out.append(ln); i += 1
    return '\n'.join(out).strip('\n')

def heading_fix(s):  # 前言：X → 前言　X
    return re.sub(r'^## (前言|导读)：', r'## \1　', s, flags=re.M)

