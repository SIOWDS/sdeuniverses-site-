def chapter(n):
    md = (SRC / ('ch%02d.md' % n)).read_text(encoding='utf-8')
    title = re.match(r'^## 第 \d+ 章　(.*)$', md.splitlines()[0])[1].strip()
    secs = re.findall(r'^### (?:◆)?(.*)$', md, re.M)
    secs = [re.sub(r'^[一二三四五六七八九十]+[、　]', '', x).strip() for x in secs]
    return title, secs


