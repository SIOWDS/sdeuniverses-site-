def main():
    p = 'public/frontier/index.html'
    h = open(p, encoding='utf-8').read()

    # ---- 前置断言 ----
    assert h.count('<<<<<<<') == 0 and h.count('>>>>>>>') == 0, '存在冲突标记'
    assert h.count('<!--PH2-END-->') == 1, 'PH2-END 锚点异常'
    assert h.count('<!--PH3-START-->') == 0, '第三期区块已存在'

    # ---- 去重校验 ----
    exist = set(re.findall(
        r'<span class="num">\d+</span><span class="nm">([^<]*)</span>', h))
    new = [n for _, lst in G for n in lst]
    assert len(new) == 200, '新增数量应为 200，实得 %d' % len(new)
    assert len(set(new)) == 200, '第三期内部有重名'
    dup = sorted(set(new) & exist)
    assert not dup, '与现有领域重名：%s' % dup
    assert sum(len(l) for _, l in G) == 200 and len(G) == 20

    # ---- 生成区块 ----
    parts = ['<!--PH3-START-->\n<div class="ph2-head"><h2>第三期 · 再两百个领域</h2><p>'
             '第三期把栏目扩到 <b>500</b> 个领域（编号 301–500）。选目<b>逐条对照麻省理工、耶鲁、康奈尔、'
             '哈佛、斯坦福、牛津、剑桥等校现行的院系与专业建制</b>补齐：一是前两期只取了主干、未展开的'
             '学科分支（数学、物理、化学、生命科学、计算机、工程各自的其余主干）；二是这些学校单独设系'
             '而前两期尚无位置的领域——临床各专科、公共卫生分支、区域研究、语言学分支、农业与应用生命'
             '科学、以及知识生产与公共治理。共 <b>200</b> 个领域，已发布 <b>0</b> · 规划中 <b>200</b>。'
             '体例与前两期相同。</p></div>\n']
    num = 301
    for name, items in G:
        parts.append('<section class="grp ph2"><h2 class="grp-t">%s <span class="grp-c">%d</span></h2><div class="grid">'
                     % (name, len(items)))
        for it in items:
            parts.append('<span class="tile plan"><span class="num">%d</span><span class="nm">%s</span>'
                         '<span class="st st-plan">规划中</span></span>' % (num, it))
            num += 1
        parts.append('</div></section>\n')
    parts.append('<!--PH3-END-->\n')
    block = ''.join(parts)
    assert num == 501, '编号应止于 500，实得 %d' % (num - 1)

    anchor = '<!--PH2-END-->\n'
    h = h.replace(anchor, anchor + block, 1)

    # ---- 改总说明 ----
    old_note = '第一期 100 个面板均已发布，可点击进入；第二期 200 个领域已规划，按类推进。'
    assert h.count(old_note) == 1
    h = h.replace(old_note,
                  '第一期 100 个面板均已发布，可点击进入；第二期 200 个领域按类推进；'
                  '第三期再增 200 个领域，选目对照全球顶尖大学现行院系建制补齐，全栏共 500 个领域。')

    # ---- 标签配平 ----
    for t in ['div', 'span', 'a', 'section', 'h2', 'p']:
        o, c = len(re.findall(r'<%s[ >]' % t, h)), len(re.findall(r'</%s>' % t, h))
        assert o == c, '%s 不配平 %d/%d' % (t, o, c)

    open(p, 'w', encoding='utf-8').write(h)

    tiles = re.findall(r'<span class="num">(\d+)</span>', h)
    print('全栏磁贴总数 %d（应为 500）' % len(tiles))
    print('第三期 20 组 × 10 = 200，编号 301–500，全部标记为规划中')
    print('去重通过：与现有 300 个领域无一重名')

main()
