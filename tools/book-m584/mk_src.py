#!/usr/bin/env python3
"""第 584 号《不再有讲课的人》：把三审后的分章稿（ch/NN.md）装成 convert.py 认的 src/。只加编首语，不动正文文字。
用法：python3 tools/book-m584/mk_src.py <分章稿目录>"""
import re, sys
from pathlib import Path
B = Path(sys.argv[1]); OUT = Path(__file__).parent / 'src'
OUT.mkdir(exist_ok=True)
for f in OUT.glob('*.md'): f.unlink()
PARTS = {
 1: ('第一编', '讲课是怎么来的：一道时差的历史', '讲课不是从来就有的样子。这一编看它怎样建在“思想在书房完成，讲台只负责搬运”这道时差上，我们后来模仿的又为什么是一个折叠版，并替它记功：它立过大功，今天也等来了比人更合身的新主人。'),
 4: ('第二编', '为什么想好了再讲不可能：根据', '这一编是全书的根据，也是全书最容易被打的地方。先说显露就是输出，再查“我早想好了”是怎么来的，问话到底是对谁说的，最后拿母题去撞它最硬的对头：太同步也是病，搁了很多年才长成的东西算什么。'),
 8: ('第三编', '拆开：只有输出的现场', '发生和输出可以被拆开，拆开了还常常很好看。这一编看四种现场：讲得太好，答案先到，写得很顺，散场就没了。每一种都查它坏在哪一处，是断了拍、缺了一式，还是走偏了路，读者可以拿自己的课来对。'),
 12: ('第四编', '合龙：说、接、认', '一次开口要算数，要有人说，有人接，自己认，三件在同一口气里合上。这一编一件一件算它们的难处：开不了口的羞耻，接不住的泄劲，认了账要付的代价；再说写也是开口，以及站在路口怎样选从哪一处开口。'),
 17: ('第五编', '不再讲课的人做什么', '这一编回答老师最关心的问题。课前备什么，还要亲口讲的地方怎样讲，老师自己被改了什么、怎样查，讲第二十遍的人累在哪里，学生不再听课以后又归谁。陆老师的处境在这一编最重，凡说得好听的地方都拿他来问一问。'),
 22: ('第六编', '假发生、读数与怎样算错', '最后一编审自己。流利可以冒充发生，读数可以被刷，这本书的写法也要过这一关。三条最强的反驳在这里说足，能答的答，答不了的写下来欠着，再把全书怎样算错一次写死。'),
}
def rd(n): return (B / ('%02d.md' % n)).read_text(encoding='utf-8').strip()
w = lambda n, s: (OUT / n).write_text(s.strip() + '\n', encoding='utf-8')
w('daolun.md', rd(0))
for n in range(1, 25):
    t = rd(n)
    assert t.startswith('# 第%d章　' % n), n
    pre = ''
    if n in PARTS:
        a, b, c = PARTS[n]
        pre = '## %s　%s\n\n%s\n\n' % (a, b, c)
    w('ch%02d.md' % n, pre + t)
w('jieyu.md', rd(25)); w('fulu1.md', rd(26)); w('fulu2.md', rd(27)); w('houji.md', rd(28)); w('shumu.md', rd(29))
print('src', len(list(OUT.glob('*.md'))))
