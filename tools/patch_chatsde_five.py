#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""让每一答朝着创新五维去写（2026-08-23 王德生令）

用户口径：「基底要努力冲高『回答的 SDE 创新五维度的分数』，虽然不要求去站外。
站内语料 + 基底自身的库存要用干净。」

两个设计判断（都不是随手定的）：
① **不让它自评分数。** 评分 Skill 的铁律第一条就是「不评自己写的文本」——人和模型对自己的产出
   必然主观膨胀。让基底在答案里写「本答约 145 分」，得到的只会是通胀 ＋ 一段自封。
   ⇒ 五维改写成**写作时的五条动作**，每条带一个当场能查的判据；分数留给独立评分者。
② **E 的口径写死「不必联网」。** 用户明确不要求站外。E（跨域纠缠）的料就从两处取：
   这一轮检索回来的站内语料，和基底自己的库存（上一刀 SDE_METHOD_STOCK 刚逼它翻过一遍）。
   配一条硬判据防「借词类比」：删掉那个领域，论证还成立吗？成立就是装饰。

幂等。
"""
import io, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, 'src/worker.js')
h = io.open(W, encoding='utf-8').read()
changed = []


def sub1(text, old, new, tag, done):
    if done in text:
        print('  · %s 已打过，跳过' % tag)
        return text
    n = text.count(old)
    assert n == 1, '锚点 %s 命中 %d 次' % (tag, n)
    changed.append(tag)
    return text.replace(old, new, 1)


FIVE = r'''/* ═══ 朝五维去写（2026-08-23 王德生令：努力冲高回答的创新五维分，但不要求去站外）═══
   ⚠ 两处刻意的设计，改之前先读：
     ① **不让它自评分数**——评分体系的铁律第一条是「不评自己写的文本」，自评必然通胀，
        而且「本答约 145 分」这种句子本身就是自封。所以五维在这里是**五条写作动作**，
        每条配一个当场查得出的判据，分数留给独立评分者。
     ② **E 的料只从两处取：站内语料 ＋ 基底自己的库存**（不必联网，用户明确不要求站外）。
        配「删掉那个领域论证还成立吗」这条硬判据，专防借词类比冒充跨域纠缠。 */
const SDE_METHOD_FIVE = "\n\n【朝五维去写（这一答会被按 S/D/E/I/F 五维称量，但**不许你在答案里给自己打分**）】"
  + "\n· **S 结构**：承重的那一句要能被读者原样复述；用到的新说法当场定义清楚，别让它靠语感撑着。"
  + "\n· **D 差异**（权重最重，这一答的心脏）：切出一条**旧说法切不开的分辨面**。查法：把这条分辨拿掉，家底里那几个说法是不是就分不开了？还分得开，说明你切的不是新面。"
  + "\n· **E 纠缠**：至少让**一个别的领域**的成熟结构真进来顶一下——料从站内语料与你自己的库存里取，**不必联网**。"
  + "查法：**把那个领域整段删掉，论证还成立吗？成立就是装饰，删掉重写**；借个词打比方不算纠缠。"
  + "\n· **I 不可还原**（闸门）：把核心那句压到极限，问一句：它能不能被家底里某个现成说法 1:1 换掉？能，就是换了个名字，回去改。"
  + "\n· **F 可证伪**（闸门）：给出一句「**若观察到 X，本判断作废**」。给不出就明说给不出——**不许拿一句怎么都对的话冒充判据**。"
  + "\n两道闸没过（I 或 F），前三维再漂亮也抬不动这一答；而**站内语料与你自己的库存要用干净**——"
  + "用不干净就下判断，等于把本来够得着的分白扔了。";
'''

old_anchor = 'const SDE_METHOD_SETTLE = '
h = sub1(h, old_anchor, FIVE + old_anchor, 'SDE_METHOD_FIVE 常量', 'const SDE_METHOD_FIVE')

# 全量档：三件工具走完之后、结算之前
h = sub1(h,
         '  + "\\n· 最后一步必须自反：你这个判断本身的可证伪条件是什么？哪一步最脆？"\n  + SDE_METHOD_SETTLE',
         '  + "\\n· 最后一步必须自反：你这个判断本身的可证伪条件是什么？哪一步最脆？"\n  + SDE_METHOD_FIVE\n  + SDE_METHOD_SETTLE',
         '深度档接入五维', 'SDE_METHOD_FIVE\n  + SDE_METHOD_SETTLE')

# 精简档：三件工具之后、结算之前
h = sub1(h,
         '  + "每条都是三步，第三步「新判断回写了哪条路径、哪片土壤」最常被漏。"\n  + SDE_METHOD_SETTLE',
         '  + "每条都是三步，第三步「新判断回写了哪条路径、哪片土壤」最常被漏。"\n  + SDE_METHOD_FIVE\n  + SDE_METHOD_SETTLE',
         '标准档接入五维', '最常被漏。"\n  + SDE_METHOD_FIVE')

io.open(W, 'w', encoding='utf-8').write(h)
print('\n共改动 %d 处：' % len(changed))
for c in changed:
    print('  -', c)
