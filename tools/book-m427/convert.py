    out = ['# ' + title, ''] + [p + '\n' for p in intro]
    for n in chs:
        h, b = body_of(n)
        out += [h, '', b, '']
    s = '\n'.join(out).rstrip() + '\n'
    (HERE / 'parts' / (fn + '.md')).write_text(s, encoding='utf-8')
    book.append(s)

