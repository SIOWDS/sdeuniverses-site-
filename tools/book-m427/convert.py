def body_of(n):
    t = (SRC / ('ch%02d.md' % n)).read_text(encoding='utf-8').strip()
    head, _, rest = t.partition('\n')
    m = re.match(r'# 第(\d+)章　(.*)$', head)
    assert m and int(m.group(1)) == n, head
    rest = re.sub(r'^### (.+)$', r'### \1', rest, flags=re.M)
    rest = re.sub(r'^## (.+)$', r'### ◆ \1', rest, flags=re.M)
    return '## 第%d章　%s' % (n, m.group(2)), rest.strip()


