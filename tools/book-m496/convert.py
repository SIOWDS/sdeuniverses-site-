def conv_body(text, top_h2=True):
    """章内转写：## → ###；带走的话 / 小账 / 可检验的小预言 → 引用块；这一章的问题 → 提问框。"""
    L = text.split('\n'); out = []; i = 0
    while i < len(L):
        l = L[i]
        m = re.match(r'^## (带走的话|小账|可检验的小预言)\s*$', l)
        if m:
            i += 1; paras = []
            while i < len(L) and not L[i].startswith('#'):
                if L[i].strip(): paras.append(L[i].strip())
                i += 1
            out.append('> **%s**' % m.group(1))
            for p in paras:
                out += ['> ' + p, '>']
            out.append('')
            continue
        m = re.match(r'^\*{0,2}这一章的问题\*{0,2}：(.*)$', l)
        if m:
            out += ['> **这一章的问题**：' + m.group(1).strip().strip('*'), '']; i += 1; continue
        if l.startswith('## '):
            out.append('#' + l); i += 1; continue
        out.append(l); i += 1
    return '\n'.join(out).strip('\n') + '\n'


