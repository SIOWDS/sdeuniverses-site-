def rings(cx, cy, r):
    ticks = []
    for k in range(72):
        a = k * math.pi * 2 / 72
        r1 = r * (1.035 if k % 6 else 1.06)
        ticks.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f"/>' % (
            cx + r * math.cos(a), cy + r * math.sin(a), cx + r1 * math.cos(a), cy + r1 * math.sin(a)))
    return f"""
<circle cx="{cx}" cy="{cy}" r="{r*1.55:.0f}" fill="url(#halo{{uid}})"/>
<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{GOLD}" stroke-opacity=".55" stroke-width="2.2"/>
<circle cx="{cx}" cy="{cy}" r="{r*1.10:.0f}" fill="none" stroke="{GOLD}" stroke-opacity=".22" stroke-width="1.2"/>
<circle cx="{cx}" cy="{cy}" r="{r*0.62:.0f}" fill="none" stroke="{CYAN}" stroke-opacity=".16" stroke-width="1.2" stroke-dasharray="3 9"/>
<g stroke="{GOLD}" stroke-opacity=".45" stroke-width="1.6">{''.join(ticks)}</g>"""


def art(W, H, uid):
    """主图：寺前一根幡竿，一面长幡被风吹起；三道风线从左边穿过幡身；幡下一个小小的人形坐着看。
    幡、风、看的人三处各一个亮点，三条细线两两相连成一个三角（三处互相需要），不指向任何一个中心。"""
    s = W / 1700
    cx, cy, r = W * 0.60, H * 0.56, 520 * s
    u = r / 450
    out = [rings(cx, cy, r).replace('{uid}', uid)]
    # 幡竿
    px, ptop, pbot = cx - 150 * u, cy - 400 * u, cy + 330 * u
    out.append(f'<rect x="{px-7*u:.0f}" y="{ptop:.0f}" width="{14*u:.0f}" height="{pbot-ptop:.0f}" rx="{6*u:.0f}" fill="{GOLD}"/>')
    out.append(f'<circle cx="{px:.0f}" cy="{ptop-14*u:.0f}" r="{18*u:.0f}" fill="{GOLD2}"/>')
    # 幡身：从竿顶向右飘的长条，两道波
    pts_top, pts_bot = [], []
    for k in range(41):
        t = k / 40
        x = px + 10 * u + t * 520 * u
        wave = math.sin(t * math.pi * 2.2 + .4) * 46 * u * (0.3 + t)
        yt = ptop + 20 * u + t * 120 * u + wave
        width = (150 - 70 * t) * u
        pts_top.append((x, yt)); pts_bot.append((x, yt + width))
    d = 'M' + ' L'.join('%.1f %.1f' % q for q in pts_top) + ' L' + ' L'.join('%.1f %.1f' % q for q in pts_bot[::-1]) + ' Z'
    out.append(f'<path d="{d}" fill="url(#kite{uid})"/>')
    # 幡上三道横纹
    for k, f in enumerate((.28, .52, .76)):
        a, b = int(f * 40), int(f * 40)
        x0, y0 = pts_top[a]; x1, y1 = pts_bot[b]
        out.append(f'<line x1="{x0:.0f}" y1="{y0+6*u:.0f}" x2="{x1:.0f}" y2="{y1-6*u:.0f}" stroke="{NAVY_MID}" stroke-opacity=".35" stroke-width="{4*s:.1f}"/>')
    # 风线
    for k, (yy, op, ln) in enumerate([(-250, .75, 760), (-120, .55, 680), (10, .35, 600)]):
        y0 = cy + yy * u
        pts = [(cx - 520 * u + t * ln * u, y0 + math.sin(t * 5.2 + k) * 26 * u) for t in [i / 30 for i in range(31)]]
        out.append(f'<path d="{tapered(pts, 9*s, 1.2*s)}" fill="{CYAN}" fill-opacity="{op}"/>')
    # 看的人：一个小小的坐像
    hx, hy = cx + 120 * u, cy + 260 * u
    out.append(f'<circle cx="{hx:.0f}" cy="{hy-70*u:.0f}" r="{24*u:.0f}" fill="{CREAM}"/>')
    out.append(f'<path d="M{hx-60*u:.0f} {hy+20*u:.0f} C{hx-50*u:.0f} {hy-50*u:.0f} {hx+50*u:.0f} {hy-50*u:.0f} {hx+60*u:.0f} {hy+20*u:.0f} Z" fill="{CREAM}" fill-opacity=".92"/>')
    # 三个亮点：风、幡、心，两两相连
    nodes = [(cx - 430 * u, cy - 250 * u, CYAN), (cx + 330 * u, cy - 330 * u, GOLD2), (hx + 200 * u, hy - 160 * u, CREAM)]
    for a in range(3):
        for b in range(a + 1, 3):
            (x1, y1, _), (x2, y2, _) = nodes[a], nodes[b]
            out.append(f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y2:.0f}" stroke="{CREAM}" stroke-opacity=".30" stroke-width="{3*s:.1f}" stroke-dasharray="{14*s:.1f} {10*s:.1f}"/>')
    for (nx, ny, col) in nodes:
        out.append(f'<circle cx="{nx:.0f}" cy="{ny:.0f}" r="{28*s:.1f}" fill="{col}"/><circle cx="{nx:.0f}" cy="{ny:.0f}" r="{52*s:.1f}" fill="none" stroke="{col}" stroke-opacity=".5" stroke-width="{3*s:.1f}"/>')
    return ''.join(out)


def barcode(x, y, s):
    if not re.search(r'\d{13}', re.sub(r'\D', '', ISBN) or ''):
        return '', 0
    d, bits = ean13_bits(ISBN)
    mw = 3.3 * s  # 模块宽
    h = 190 * s
    rects = []
    for i, b in enumerate(bits):
        if b == '1':
            guard = i < 3 or 45 <= i < 50 or i >= 92
            rects.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#111"/>' % (x + 22 * s + i * mw, y + 40 * s, mw + .2, h + (18 * s if guard else 0)))
    bw = 95 * mw + 44 * s
    txt = (f'<text x="{x + bw/2:.0f}" y="{y + 30*s:.0f}" font-size="{19*s:.0f}" text-anchor="middle" font-family="Noto Sans CJK SC" fill="#111">ISBN {ISBN}</text>'
           f'<text x="{x + 8*s:.0f}" y="{y + 40*s + h + 36*s:.0f}" font-size="{26*s:.0f}" font-family="Noto Serif CJK SC" fill="#111">{d[0]}</text>'
           f'<text x="{x + 22*s + 3*mw + 21*mw:.0f}" y="{y + 40*s + h + 36*s:.0f}" font-size="{26*s:.0f}" text-anchor="middle" letter-spacing="{9*s:.0f}" font-family="Noto Serif CJK SC" fill="#111">{d[1:7]}</text>'
           f'<text x="{x + 22*s + 50*mw + 21*mw:.0f}" y="{y + 40*s + h + 36*s:.0f}" font-size="{26*s:.0f}" text-anchor="middle" letter-spacing="{9*s:.0f}" font-family="Noto Serif CJK SC" fill="#111">{d[7:]}</text>')
    return (f'<rect x="{x:.0f}" y="{y:.0f}" width="{bw:.0f}" height="{h + 110*s:.0f}" fill="#fff"/>' + ''.join(rects) + txt), bw


