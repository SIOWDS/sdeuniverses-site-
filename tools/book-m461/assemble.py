def norm_head(t):
    return re.sub(r'^## 第 ?(\d+) ?章[　 ]+', lambda m: '## 第 %s 章　' % m[1], t, count=1, flags=re.M)


def main():
    (HERE / 'parts').mkdir(exist_ok=True)
    allp = []
    for k, (title, rng, intro) in enumerate(PARTS):
        chs = [norm_head((HERE / ('chapters/ch%02d.md' % n)).read_text().strip()) for n in rng]
        body = '# 第%s编　%s\n\n%s\n\n%s\n' % (CN[k], title, '\n\n'.join(intro), '\n\n'.join(chs))
        body = re.sub(r'\n{3,}', '\n\n', body)
        name = 'parts/%02d-第%s编.md' % (k + 1, CN[k])
        (HERE / name).write_text(body)
        allp.append(body)
    (HERE / 'book.md').write_text('\n\n'.join(p.strip() for p in allp) + '\n')
    han = len(re.findall(r'[一-鿿]', '\n'.join(allp)))
    print('parts', len(allp), 'chapters', sum(len(list(p[1])) for p in PARTS), 'han', han)


if __name__ == '__main__':
    main()
