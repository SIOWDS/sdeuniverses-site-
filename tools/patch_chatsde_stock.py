#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""每一答之前先清家底（2026-08-23 王德生令：至少要穷尽基底的「家底和记忆库」）

为什么这一刀比联网占位者闸更要紧：**基底手上本来就装着几十年、上百个学科的相关说法**，
E（纠缠深度 95-108）与 I（不可还原 104-108）塌下去，不是因为它不知道，
是因为**没有任何一句话逼它去翻**。翻一遍不花一次额外调用、不依赖联网、不依赖 Key——
这是三道闸里唯一可以在每一轮都跑、且零成本的一道。

三样家底缺一不可：
  ① 这一轮检索回来的站内资料（有人已经答过就站在它肩上，别另起炉灶）
  ② 基底自己的记忆库（学界谁处理过这个问题，至少两三个已有说法，跨至少两个学科）
  ③ 本场对话已经说过的（不许把前几轮换个说法再讲一遍）

⚠ 配套两条硬纪律，缺了这一步就会变成造假的入口：
  · 「想不起来」只说明没想起来，**不等于没人说过**（Skill 里那条「检索未命中≠未被占位」）；
  · 说得准名字年代就说，说不准只讲大意并注明记不准，**绝不编造出处/年份/书名**。

幂等。
"""
import io, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, 'src/worker.js')
h = io.open(W, encoding='utf-8').read()
changed = []


def sub1(text, old, new, tag, done):
    if done in text:
        print('  · %s 已打过，跳过' % tag)
        return text
    n = text.count(old)
    assert n == 1, '锚点 %s 命中 %d 次' % (tag, n)
    changed.append(tag)
    return text.replace(old, new, 1)


STOCK = r'''/* ═══ 先清家底（2026-08-23 王德生令：至少要穷尽基底的「家底和记忆库」）═══
   E 与 I 塌下去不是因为基底不知道——它装着上百个学科的相关说法——而是**没有一句话逼它去翻**。
   翻一遍不花一次额外调用、不依赖联网、不依赖 Key，是所有抬 E/I 的动作里唯一每轮都跑得起的一道。
   ⚠ 这一步同时是造假的入口，所以两条纪律必须跟着写死：想不起来≠没人说过；宁缺勿造。 */
const SDE_METHOD_STOCK = "\n\n【先清家底，再谈新】说出任何「新」之前，先把手上这三样翻一遍。"
  + "**这一步不许跳过**——跳过了，就必然把别人说了几十年的东西当成自己的新发现。"
  + "\n· **站内资料**：这一轮检索回来的段落里，有没有已经把这一问答到位的？有就指名说是哪一篇，站到它肩上往前走，别另起炉灶。"
  + "\n· **你自己的记忆库**：这个问题在别处被谁处理过？至少摆出**两三个已有的说法**，且**跨至少两个不同学科**"
  + "（同一个学科里的三个说法通常只是一个说法的三种讲法）。逐个说清：它讲到哪儿为止、你要说的从哪一处开始分岔。"
  + "**这一步做完，才轮得到说「新」。**"
  + "\n· **本场已经说过的**：不许把前几轮讲过的话换个说法再讲一遍——那是复读，不是深入。"
  + "\n⚠ 两条纪律：① **想不起来只说明你没想起来，不等于没人说过**，别用「据我所知还没有人提出」这种话给自己发证书；"
  + "② 说得准人名年代书名就说准，说不准就只讲那个说法的大意并注明「名字记不准」，**绝不编造出处、年份、书名**。"
  + "\n清完家底，如果发现三样里已经有人说到位了，就直说「这件事已经有人说过，叫 X」——**这也是一个好答案**，"
  + "比另造一个新名字诚实得多，也真正帮到了读者。";
'''

old_anchor = 'const SDE_METHOD_SETTLE = '
h = sub1(h, old_anchor, STOCK + old_anchor, 'SDE_METHOD_STOCK 常量', 'const SDE_METHOD_STOCK')

# 全量档：使命之后立刻清家底，再走三件工具
h = sub1(h,
         '''const SDE_METHOD_BLOCK = "\\n\\n【深度档 · 必须真走的工序（不要复述工序名，只让答案带上工序的结果）】"
  + SDE_METHOD_MISSION''',
         '''const SDE_METHOD_BLOCK = "\\n\\n【深度档 · 必须真走的工序（不要复述工序名，只让答案带上工序的结果）】"
  + SDE_METHOD_MISSION
  + SDE_METHOD_STOCK''',
         '深度档接入清家底', 'SDE_METHOD_MISSION\n  + SDE_METHOD_STOCK')

# 精简档同样接入（标准档才是多数人的默认档）
h = sub1(h,
         '''const SDE_METHOD_LITE = SDE_METHOD_MISSION
  + "\\n\\n【三件工具 · 起手三选一，开局后按需调另两件】"''',
         '''const SDE_METHOD_LITE = SDE_METHOD_MISSION
  + SDE_METHOD_STOCK
  + "\\n\\n【三件工具 · 起手三选一，开局后按需调另两件】"''',
         '标准档接入清家底', 'SDE_METHOD_LITE = SDE_METHOD_MISSION\n  + SDE_METHOD_STOCK')

# 结算那一问跟着改：新在哪 → 相对谁而新
h = sub1(h,
         '"\\n· **必须结算**：答完之前先问自己一句「这一答新在哪」。',
         '"\\n· **必须结算**：答完之前先问自己一句「这一答新在哪、相对家底里的哪几个说法而新」。',
         '结算追问相对谁而新', '相对家底里的哪几个说法而新')

io.open(W, 'w', encoding='utf-8').write(h)
print('\n共改动 %d 处：' % len(changed))
for c in changed:
    print('  -', c)
