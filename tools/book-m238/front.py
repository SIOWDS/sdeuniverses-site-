    rows = []
    for m in re.finditer(r'^## 第 (\d+) 章　([^：]+)：(.*)$', t, re.M):
        n = int(m[1])
        rev = next(k for k, (a, b) in sec.items() if a <= n <= b)
        rows.append('| %s | 第 %d 章 | %s | %s |' % (m[2], n, rev, m[3]))
    return rows


